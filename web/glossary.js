// Links work as ordinary anchors first. The optional dialog keeps a definition beside the
// reader's lesson; its words come from the same Markdown as the full glossary.
(() => {
  const field = document.getElementById("glossary-search");
  if (field) {
    const entries = [...document.querySelectorAll(".glossary-entry")];
    const alphabet = document.querySelector(".glossary-alphabet");
    const status = document.getElementById("glossary-status");
    const normalise = (text) => text.toLocaleLowerCase().replace(/[_‑–-]+/g, " ").replace(/[’']/g, "");
    const apply = () => {
      const words = normalise(field.value).trim().split(/\s+/).filter(Boolean);
      let found = 0;
      for (const entry of entries) {
        const text = normalise(`${entry.dataset.aliases} ${entry.textContent}`);
        entry.hidden = !words.every((word) => text.includes(word));
        if (!entry.hidden) found++;
      }
      for (const letter of document.querySelectorAll(".glossary-letter")) {
        letter.hidden = !entries.some((entry) => !entry.hidden && entry.dataset.letter === letter.textContent);
      }
      alphabet.hidden = words.length > 0;
      status.textContent = !words.length ? `${entries.length} terms`
        : !found ? "No matching terms. Try a shorter word or clear the search."
        : `${found} matching ${found === 1 ? "term" : "terms"}`;
    };
    field.closest(".glossary-search").hidden = false;
    field.addEventListener("input", apply);
    addEventListener("hashchange", () => {
      // A deep link must remain reachable even if the reader had filtered it out.
      let id;
      try { id = decodeURIComponent(location.hash.slice(1)); } catch { return; }
      const target = document.getElementById(id);
      if (target) { field.value = ""; apply(); target.scrollIntoView(); }
    });
    apply();
  }

  if (!window.HTMLDialogElement || !HTMLDialogElement.prototype.showModal) return;
  let definitions, dialog, trigger;
  const lookup = () => definitions ||= fetch("glossary.json")
    .then((response) => { if (!response.ok) throw new Error("glossary unavailable"); return response.json(); })
    .catch((error) => { definitions = null; throw error; });
  document.addEventListener("click", async (event) => {
    const link = event.target.closest("a.term-link");
    if (!link || event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    try {
      const id = new URL(link.href).hash.slice(1);
      const entry = (await lookup())[id];
      if (!entry) throw new Error("definition unavailable");
      if (!dialog) {
        dialog = document.createElement("dialog");
        dialog.className = "term-dialog";
        dialog.setAttribute("aria-labelledby", "term-dialog-title");
        dialog.innerHTML = '<div class="term-dialog-heading"><h2 id="term-dialog-title"></h2>'
          + '<button type="button" class="term-close" aria-label="Close definition">✕</button></div>'
          + '<div class="term-definition"></div><p class="term-full"><a>Open in the glossary</a></p>';
        dialog.querySelector(".term-close").addEventListener("click", () => dialog.close());
        dialog.addEventListener("close", () => trigger?.focus({ preventScroll: true }));
        document.body.append(dialog);
      }
      if (!dialog.open) trigger = link;
      dialog.querySelector("h2").textContent = entry.title;
      // HTML is generated by the repository's escaping renderer, never from search input.
      dialog.querySelector(".term-definition").innerHTML = entry.body;
      dialog.querySelector(".term-full a").href = entry.href;
      if (!dialog.open) dialog.showModal();
      dialog.querySelector(".term-close").focus({ preventScroll: true });
    } catch {
      location.assign(link.href);
    }
  });
})();
